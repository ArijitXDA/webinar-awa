/**
 * Check if role1 has higher hierarchy than role2
 * @param role1 - First role
 * @param role2 - Second role
 * @returns True if role1 is higher
 */
function isHigherRole(role1: string, role2: string): boolean {
  const level1 = ROLE_HIERARCHY[role1 as JobRole] || 0
  const level2 = ROLE_HIERARCHY[role2 as JobRole] || 0
  return level1 > level2
}

/**
 * Check if employee can view analytics
 * @param employee - Current employee
 * @param targetEmployeeId - Optional target employee for filtered analytics
 * @returns Permission check result
 */
export async function canViewAnalytics(
  employee: Employee,
  targetEmployeeId?: string
): Promise<PermissionCheck> {
  // Top management can view all analytics
  if (isTopManagement(employee.job_role)) {
    return { canView: true, canEdit: false, canDelete: false, canAssign: false }
  }

  // Managers can view their team's analytics
  if (isManager(employee.job_role)) {
    if (!targetEmployeeId) {
      return { canView: true, canEdit: false, canDelete: false, canAssign: false }
    }

    const subordinates = await getSubordinates(employee.id)
    if (targetEmployeeId === employee.id || subordinates.includes(targetEmployeeId)) {
      return { canView: true, canEdit: false, canDelete: false, canAssign: false }
    }
  }

  // Regular employees can only view their own analytics
  if (!targetEmployeeId || targetEmployeeId === employee.id) {
    return { canView: true, canEdit: false, canDelete: false, canAssign: false }
  }

  return {
    canView: false,
    canEdit: false,
    canDelete: false,
    canAssign: false,
    reason: 'Insufficient permissions to view analytics for this employee',
  }
}

/**
 * Check if employee can perform bulk operations
 * @param employee - Current employee
 * @returns True if can perform bulk operations
 */
export function canPerformBulkOperations(employee: Employee): boolean {
  // Only managers and above can perform bulk operations
  return isManager(employee.job_role)
}
